/**
 * report.js — Printable calculation report with traceability
 *
 * REPORT.print(spec) builds a formal, print-only report (header with timestamp
 * and database version, input parameters, results, method, data sources and
 * disclaimer) and opens the browser print dialog. The report node is removed
 * after printing; the screen layout is untouched.
 *
 * spec = {
 *   title:    'External Dose Estimate',         // report heading
 *   nuclide:  { id, name, half_life_display, source, _icrp107 },
 *   sections: [ { heading, rows: [[label, value], ...] }, ... ],
 *   notes:    [ 'method / warning strings', ... ],
 *   sources:  [ 'reference strings', ... ],     // appended to the common ones
 *   // Optional, for reports that are not about one point-source nuclide:
 *   headerRows: [[label, value], ...],           // replace the Nuclide / Data status rows
 *   disclaimer: 'text',                          // replaces the point-source DISCLAIMER
 *   omitCommonSources: true,                     // a report that uses no decay data
 *                                                // (caregiver: measured rate and
 *                                                // effective half-lives only)
 * }
 *
 * All values are rendered as escaped text — pass plain strings.
 */

'use strict';

const REPORT = (() => {

  // Only the source every report actually uses (decay data: half-lives,
  // emissions). ICRU 57 / Cornejo used to be listed here unconditionally, which
  // over-attributed them to reports that never touch conversion coefficients —
  // the Y-90 container estimates (no primary source at all) and plain decay
  // calculations (re-audit 2026-07-16, R-02). Scenario-specific sources are the
  // caller's responsibility via spec.sources.
  const COMMON_SOURCES = [
    'ICRP Publication 107 (2008) — Nuclear Decay Data for Dosimetric Calculations.',
  ];

  const DISCLAIMER =
    'Point-source estimate for radiation protection planning. Geometry, scatter, build-up and ' +
    'source-distribution effects are not modelled unless stated. NOT valid for patient dosimetry or ' +
    'treatment planning. Results must be reviewed by a qualified medical physics / radiation ' +
    'protection expert before regulatory or clinical use. Generated by NM Radionuclide Planner, an ' +
    'open-source reference tool provided without warranty of any kind.';

  function esc(s) {
    return String(s ?? '—')
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /**
   * Per-nuclide data status for the report header.
   *
   * This used to print "Curated database entry (validated against published
   * sources)" for EVERY curated entry — including the Y-90 container estimates,
   * which have no primary source at all, and Ra-223, whose constant sits ~6%
   * from the published one. A signed, printed report must not overstate what was
   * actually checked (audit 2026-07-15, finding 6), so the status is now derived
   * per nuclide from the provenance already stored in nuclides.json.
   *
   * @param {object} n - nuclide record
   * @returns {string}
   */
  function validationStatus(n) {
    if (n.id === 'Y-90') {
      return 'ESTIMATE, no primary source — container bremsstrahlung constants follow the Zanzonico et al. (1999) methodology, but that publication tabulates soft tissue and bone only, not these container geometries. Not validated; no regulatory verdict is issued for this nuclide';
    }
    if (n._icrp107) {
      return 'ICRP 107 extended entry — constants computed from the ICRP 107 photon spectrum, NOT manually validated against a published constant';
    }
    const cv = n.cornejo_validation;
    const published = cv && cv.gamma_H10_Cornejo;
    if (published && Number.isFinite(n.gamma_H10)) {
      const dev = 100 * (n.gamma_H10 - published) / published;
      const sign = dev >= 0 ? '+' : '−';
      const agrees = Math.abs(dev) <= 2;
      return `Curated entry, cross-checked against ${cv.source || 'Cornejo et al. (2015)'}: published Γ^H*(10) = ${UTILS.num(published)}, stored ${UTILS.num(n.gamma_H10)} (${sign}${UTILS.dec(Math.abs(dev).toFixed(1))}%)`
        + (agrees ? '' : ' — difference not reconciled');
    }
    return 'Curated entry computed from ICRP 107 photon data with ICRP 74 Table A.21 coefficients — no published comparison is recorded in this app';
  }

  /**
   * Provenance of the half-life: per-nuclide `half_life_source` for curated
   * entries (ICRP 107 or DDEP, audit 2026-10-14, N-03); ICRP 107 for extended ones.
   */
  function halfLifeSource(n) {
    if (n._icrp107) return 'ICRP Publication 107 (2008), extended entry — not manually validated';
    return n.half_life_source || 'Curated database entry — no half-life source recorded';
  }

  function buildHtml(spec) {
    const meta = (typeof DB !== 'undefined' && DB.getMeta) ? DB.getMeta() : {};
    const now  = new Date();
    // Both instants labelled: the ISO one is UTC, the other local with its zone
    // (copy audit 2026-10-03, T36).
    let zone = '';
    try { zone = Intl.DateTimeFormat().resolvedOptions().timeZone || ''; } catch (e) { /* no Intl */ }
    const ts   = now.toISOString().slice(0, 19) + 'Z (UTC); local: ' + now.toLocaleString() + (zone ? ' (' + zone + ')' : '');
    const n    = spec.nuclide || {};
    // The per-nuclide status describes the stored Γ constants. A report built
    // on other coefficients (e.g. the sludge scenario) passes its own headerRows
    // instead, so that status is never printed against data it does not cover.
    const nuclideRows = spec.headerRows
      ? spec.headerRows.map(([k, v]) => `<tr><td>${esc(k)}</td><td>${esc(v)}</td></tr>`).join('')
      : spec.kind === 'decay'
      // A decay report depends on the half-life only: the status of the Γ
      // constants (and the Y-90 container warning) does not belong in it
      // (copy audit 2026-10-03, T34).
      ? `<tr><td>Nuclide</td><td><strong>${esc(n.id)}</strong> — ${esc(n.name)} (T&#189; = ${esc(UTILS.dec(n.half_life_display))})</td></tr>
          <tr><td>Half-life source</td><td>${esc(halfLifeSource(n))}</td></tr>`
      : `<tr><td>Nuclide</td><td><strong>${esc(n.id)}</strong> — ${esc(n.name)} (T&#189; = ${esc(UTILS.dec(n.half_life_display))})</td></tr>
          <tr><td>Half-life source</td><td>${esc(halfLifeSource(n))}</td></tr>
          <tr><td>Data status</td><td>${esc(validationStatus(n))}</td></tr>
          ${n.source ? `<tr><td>Nuclide source</td><td>${esc(n.source)}</td></tr>` : ''}`;

    // Identify the CODE, not just the data: two app versions sharing the same
    // nuclides.json must not produce indistinguishable reports (audit
    // 2026-07-16, H-07). UTILS.APP_BUILD is kept equal to sw.js CACHE_VERSION.
    const appVersion = (typeof UTILS !== 'undefined' && UTILS.APP_VERSION) || '?';
    const appBuild = (typeof UTILS !== 'undefined' && UTILS.APP_BUILD) || '?';

    let html = `
      <div class="rpt-header">
        <div class="rpt-title">&#9762; NM Radionuclide Planner — ${esc(spec.title)}</div>
        <table class="rpt-meta">
          <tr><td>Generated</td><td>${esc(ts)}</td></tr>
          <tr><td>Application</td><td>NM Radionuclide Planner v${esc(appVersion)} (build ${esc(appBuild)})</td></tr>
          ${typeof DB !== 'undefined' ? (spec.nuclide && spec.nuclide._icrp107
            // an extended nuclide does not come from the curated database (F-02)
            ? `<tr><td>Database</td><td>ICRP 107 extended index (the curated nuclides.json v${esc(meta.version || '?')} is not used for this nuclide)</td></tr>`
            : `<tr><td>Database</td><td>nuclides.json v${esc(meta.version || '?')} — ${esc(meta.reference ? String(meta.reference).slice(0, 90) : '')}&hellip;</td></tr>`) : ''}
          ${nuclideRows}
        </table>
      </div>`;

    for (const sec of spec.sections || []) {
      html += `<div class="rpt-section"><div class="rpt-heading">${esc(sec.heading)}</div><table class="rpt-table">`;
      for (const [k, v] of sec.rows || []) {
        html += `<tr><td>${esc(k)}</td><td>${esc(v)}</td></tr>`;
      }
      html += `</table></div>`;
    }

    if (spec.notes && spec.notes.length) {
      html += `<div class="rpt-section"><div class="rpt-heading">Method &amp; warnings</div><ul class="rpt-list">`;
      for (const note of spec.notes) html += `<li>${esc(note)}</li>`;
      html += `</ul></div>`;
    }

    html += `<div class="rpt-section"><div class="rpt-heading">Data sources</div><ul class="rpt-list">`;
    for (const src of (spec.omitCommonSources ? [] : COMMON_SOURCES).concat(spec.sources || [])) html += `<li>${esc(src)}</li>`;
    html += `</ul></div>`;

    html += `
      <div class="rpt-disclaimer"><strong>Disclaimer.</strong> ${esc(spec.disclaimer || DISCLAIMER)}</div>
      <div class="rpt-sign">
        <div>Reviewed by (name / signature): ______________________________</div>
        <div>Date: ____________</div>
      </div>`;

    return html;
  }

  function print(spec) {
    const old = document.getElementById('printReport');
    if (old) old.remove();
    const div = document.createElement('div');
    div.id = 'printReport';
    div.innerHTML = buildHtml(spec);
    document.body.appendChild(div);
    document.body.classList.add('print-report-mode');

    const cleanup = () => {
      document.body.classList.remove('print-report-mode');
      div.remove();
      window.removeEventListener('afterprint', cleanup);
    };
    window.addEventListener('afterprint', cleanup);
    window.print();
    // Safari/file:// may not fire afterprint reliably — defensive cleanup
    setTimeout(cleanup, 2000);
  }

  return { print };

})();
